def _read_prediction_file(filename):
    return pd.read_csv(filename)


def _error_column(df, sym_name, upper_name, lower_name):
    if sym_name in df.columns:
        return pd.to_numeric(df[sym_name], errors='coerce')
    return (
        pd.to_numeric(df[upper_name], errors='coerce')
        + pd.to_numeric(df[lower_name], errors='coerce')
    ) / 2


def prepare_new_stars(filename):
    raw = _read_prediction_file(filename)
    train_df = get_dataset(TRAINING_FILE, 'MS')
    mteff, mmet, mlum, mtmass, steff, smet, slum, smass = return_norm(train_df)

    teff = pd.to_numeric(raw['Teff'], errors='coerce')
    meta = pd.to_numeric(raw['Meta'], errors='coerce')
    lum = pd.to_numeric(raw['L'], errors='coerce')
    eteff = _error_column(raw, 'eTeff', 'eTeff1', 'eTeff2')
    emeta = _error_column(raw, 'eMeta', 'eMeta1', 'eMeta2')
    elum = _error_column(raw, 'eL', 'eL1', 'eL2')

    keep = teff.notna() & meta.notna() & lum.notna() & eteff.notna() & emeta.notna() & elum.notna()

    X = pd.DataFrame({
        'Teff': (teff[keep] - mteff) / steff,
        'Meta': (meta[keep] - mmet) / smet,
        'L': (lum[keep] - mlum) / slum,
    })
    X_er = pd.DataFrame({
        'eTeff': abs(eteff[keep]) / steff,
        'eMeta': abs(emeta[keep]) / smet,
        'eL': abs(elum[keep]) / slum,
    })

    id_col = 'SIMBAD_ID' if 'SIMBAD_ID' in raw.columns else 'ID' if 'ID' in raw.columns else 'Seq'
    ids = raw.loc[keep, id_col] if id_col in raw.columns else raw.index[keep]
    return X, X_er, ids


def main():
    df_train = get_dataset(TRAINING_FILE, 'MS')
    (x_train, x_train_er, x_test, x_test_err, mass_train, emass_train,
      mass_test, emass_test
    ) = return_train_test(df_train)
    unorm_mass = denormalise_val(mass_test, 'mass')

    x_train = x_train[['Teff', 'Meta', 'L']]
    x_train_er = x_train_er[['eTeff', 'eMeta', 'eL']]
    X = x_test[['Teff', 'Meta', 'L']]
    X_er = x_test_err[['eTeff', 'eMeta', 'eL']]

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    bart_model = bart.BART_M(x_train, x_train_er, mass_train, emass_train)
    bart_pred, lpd_BART = sample_pred_BART(
        bart_model,
        X,
        X_er,
        'mass',
        3000,
        4,
        trace_filename=BART_TRACE_FILE,
        predictions_filename=BART_PREDICTIONS_FILE,
    )

    gp_model, mu_gp, log_var_gp, Xu, Xu_er = gp.sparse_fully_heteroscedastic_gp(
        x_train, x_train_er, mass_train, 80, 40
    )
    gp_trace = az.from_netcdf(GP_TRACE_FILE)
    gp_pred, lpd_GP = posterior_predictive_GP(
        gp_model, mu_gp, log_var_gp, gp_trace,
        X, X_er, Xu, Xu_er, 3, 'mass'
    )

    hbnn_trace = az.from_netcdf(HBNN_TRACE_FILE)
    hbnn_pred, lpd_HBNN = sample_post_pred_HBNN_para(
        hbnn_trace, X, X_er, 15, 3, 'mass'
    )

    bhs_trace, bhs_pred, bhs_w = run_stack(
        bart_pred, hbnn_pred, gp_pred,
        x_train, X, lpd_BART, lpd_HBNN, lpd_GP,
        draws=3000, chains=4
    )
    bhs_trace.to_netcdf(BHS_TRACE_FILE)

    print('MAE BART:', mean_absolute_error(unorm_mass, bart_pred.mean(0)))
    print('MARD BART:', mard(unorm_mass, bart_pred.mean(0)))
    print('MRD BART:', mrd(unorm_mass, bart_pred.mean(0)))
    print('MAE GP:', mean_absolute_error(unorm_mass, gp_pred.mean(0)))
    print('MARD GP:', mard(unorm_mass, gp_pred.mean(0)))
    print('MRD GP:', mrd(unorm_mass, gp_pred.mean(0)))
    print('MAE HBNN:', mean_absolute_error(unorm_mass, hbnn_pred.mean(0)))
    print('MARD HBNN:', mard(unorm_mass, hbnn_pred.mean(0)))
    print('MRD HBNN:', mrd(unorm_mass, hbnn_pred.mean(0)))
    print('MAE BHS:', mean_absolute_error(unorm_mass, bhs_pred.mean(0)))
    print('MARD BHS:', mard(unorm_mass, bhs_pred.mean(0)))
    print('MRD BHS:', mrd(unorm_mass, bhs_pred.mean(0)))

    results = pd.DataFrame({
        'original_row': x_test.index,
        'M_true': np.asarray(unorm_mass),
        'BART_pred': bart_pred.mean(0),
        'BART_pred_sigma': bart_pred.std(0),
        'BHS_pred': bhs_pred.mean(0),
        'BHS_pred_sigma': bhs_pred.std(0),
    })
    results.to_csv(BHS_RESULTS_FILE, sep='\t', index=False)

    plot_mass_diagnostics(
        unorm_mass,
        bart_pred,
        'BART',
        output_base=os.path.join(OUTPUT_DIR, 'BART_mass_3param_L_prediction_seed_176')
    )
    plot_mass_diagnostics(
        unorm_mass,
        bhs_pred,
        'BHS',
        filtered_percentiles=(95, 90),
        output_base=os.path.join(OUTPUT_DIR, 'BHS_mass_3param_L_prediction_seed_176')
    )

    print('Saved holdout results to', BHS_RESULTS_FILE)





if __name__ == '__main__':
    main()
